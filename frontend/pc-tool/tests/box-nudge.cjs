const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { inspectScene, matches } = require('./centerpoint-render.cjs');

async function main() {
    const scene = 'scene-0061';
    const input = path.join(process.env.XTREME1_DB_ROOT || path.join(os.homedir(), 'datasets/perception/xtreme1/nuscenes-v1.0-mini'), scene);
    const predictions = 'predictions/centerpoint-pubtracker';
    const pointer = JSON.parse(fs.readFileSync(path.join(input, predictions, 'active.json')));
    const tracking = path.join('runs', pointer.runId, 'tracking.json');
    const frames = JSON.parse(fs.readFileSync(path.join(input, predictions, tracking))).frames;
    const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'xtreme1-box-nudge-'));
    let server, browser;
    try {
        const output = path.join(temp, scene);
        fs.mkdirSync(path.dirname(path.join(output, predictions, tracking)), { recursive: true });
        for (const file of ['active.json', tracking]) fs.copyFileSync(path.join(input, predictions, file), path.join(output, predictions, file));
        process.env.XTREME1_SOURCE_ROOT ||= path.join(input, 'source');
        process.env.XTREME1_DB_ROOT = temp;
        process.env.XTREME1_SCENE_ID = scene;
        server = await require('vite').createServer({ root: path.resolve(__dirname, '..'), logLevel: 'error',
            cacheDir: path.join(temp, 'vite-cache'), server: { host: '127.0.0.1', port: 0, hmr: false } });
        await server.listen();
        const url = `http://127.0.0.1:${server.httpServer.address().port}/local-trial`;
        const { chromium } = require(process.env.PLAYWRIGHT_CORE || path.join(os.homedir(), '.nvm/versions/node/v22.22.2/lib/node_modules/openclaw/node_modules/playwright-core'));
        browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
        const page = await browser.newPage({ viewport: { width: 1680, height: 1000 } });
        page.setDefaultTimeout(15000);
        await page.goto(url, { waitUntil: 'domcontentloaded' });
        const car = page.locator('.cp-group[data-category="Car"]');
        await car.locator('.cp-type').click();
        const row = car.locator('.cp-row').first();
        await row.getByTestId('centerpoint-select').click();
        const scan = await page.evaluate(() => window.editor.getCurrentFrame().id);
        const sourceId = await row.getAttribute('data-candidate-id');
        const original = frames[scan].find(box => box.id === sourceId);
        const id = `centerpoint:${scan}:${sourceId}`;
        const adjusted = { ...original, center: [...original.center], size: [...original.size] };
        const panel = page.getByTestId('centerpoint-adjust');
        const plus = panel.getByRole('button', { name: '增加一步' });
        const minus = panel.getByRole('button', { name: '减少一步' });
        const undo = panel.getByRole('button', { name: '撤销上次微调' });
        const setAxis = label => panel.getByLabel('微调轴').selectOption({ label });
        const review = async action => {
            const saved = page.waitForResponse(response => new URL(response.url()).pathname === '/trial-data/reviews' && response.request().method() === 'PUT');
            const [response] = await Promise.all([saved, action()]); assert.equal(response.status(), 200);
        };
        const checkPending = async () => {
            const state = await page.evaluate(inspectScene);
            assert.equal(state.id, scan); assert.equal(state.selectedPreview, id);
            assert.ok(matches(state.previews.find(box => box.id === id), adjusted));
            assert.equal(state.sideViews.length, 3); assert.ok(state.sideViews.every(view => view.targetId === id));
            assert.equal(state.accepted.length, 0);
            const records = JSON.parse(fs.readFileSync(path.join(output, 'annotations/review-decisions.json')));
            const record = JSON.parse(Object.entries(records).find(([key]) => key.endsWith(`:${id}`))[1]);
            assert.equal(record.decision, 'adjusted'); assert.deepEqual(record.center, adjusted.center);
            assert.deepEqual(record.size, adjusted.size); assert.equal(record.yaw, adjusted.yaw);
        };
        console.log(`Reviewing ${id} in temporary database`);
        await panel.getByLabel('距离步长').selectOption('0.1');
        await review(() => plus.click()); adjusted.center[0] += 0.1;
        await review(() => plus.press('Enter')); adjusted.center[0] += 0.1;
        await setAxis('宽度'); await review(() => minus.click()); adjusted.size[1] -= 0.1;
        await setAxis('偏航'); await panel.getByLabel('角度步长').selectOption('5');
        await review(() => plus.click()); adjusted.yaw += 5 * Math.PI / 180;
        await checkPending();
        assert.ok(await undo.isEnabled(), 'the selected candidate keeps its adjustment history after redraw');
        await review(() => undo.click()); adjusted.yaw = original.yaw; await checkPending();
        console.log('PASS repeated centre, width and yaw steps, exact undo, pending disk record and three linked views');
        await page.getByTestId('trial-next').click(); await panel.waitFor({ state: 'hidden' });
        assert.notEqual(await page.evaluate(() => window.editor.getCurrentFrame().id), scan);
        await page.getByTestId('trial-prev').click();
        await page.waitForFunction(scan => window.editor.getCurrentFrame()?.id === scan, scan);
        await row.getByTestId('centerpoint-select').click(); assert.ok(await undo.isDisabled()); await checkPending();
        for (const category of ['Pedestrian', 'Motorcycle', 'Bicycle']) await page.locator(`.cp-group[data-category="${category}"] .cp-visibility`).click();
        const ids = await car.locator('.cp-row').evaluateAll(rows => rows.map(row => row.dataset.candidateId));
        const rejectId = ids[ids.length - 1];
        await review(() => car.locator('.cp-row').last().getByTestId('centerpoint-reject').click());
        const expected = ids.filter(source => source !== rejectId).map(source => `centerpoint:${scan}:${source}`);
        const confirm = page.getByTestId('centerpoint-confirm');
        assert.equal(await confirm.innerText(), `确认本帧 (${expected.length})`);
        await car.locator('.cp-type').click();
        await confirm.click();
        await page.waitForFunction(id => !document.querySelector(`.cp-row[data-candidate-id="${CSS.escape(id)}"]`), sourceId);
        const document = JSON.parse(fs.readFileSync(path.join(output, `annotations/working/${scene}.json`)));
        const saved = document.frames.find(frame => frame.scan_id === scan).boxes;
        assert.deepEqual(saved.map(box => box.bbox_id).sort(), expected.sort());
        const edited = saved.find(box => box.bbox_id === id);
        assert.deepEqual(edited.center, adjusted.center); assert.deepEqual(edited.size, adjusted.size);
        assert.ok(await confirm.isDisabled());
        console.log('PASS navigation does not accept; one confirmation saves all eligible boxes including collapsed rows, excluding rejected and hidden candidates');
        await page.evaluate(id => window.editor.pc.selectObject(window.editor.pc.getAnnotate3D().find(box => box.uuid === id)), id);
        const handle = page.locator('.side-view rect[data-info="bg"]:visible').first();
        const rect = await handle.boundingBox(); assert.ok(rect);
        const startX = rect.x + rect.width / 2, startY = rect.y + rect.height / 2;
        await page.mouse.move(startX, startY); await page.mouse.down();
        await page.mouse.move(startX + 15, startY + 8, { steps: 3 }); await page.mouse.up();
        const formal = async () => (await page.evaluate(inspectScene)).accepted.find(box => box.id === id);
        assert.notDeepEqual((await formal()).center, adjusted.center);
        await page.keyboard.press('Control+z'); assert.deepEqual((await formal()).center, adjusted.center);
        console.log('PASS formal orthographic pointer drag and Ctrl+Z');
        const pedestrian = page.locator('.cp-group[data-category="Pedestrian"]');
        await pedestrian.locator('.cp-visibility').click(); await pedestrian.locator('.cp-type').click();
        const nextRow = pedestrian.locator('.cp-row').first();
        await nextRow.getByTestId('centerpoint-select').click();
        assert.equal(await nextRow.getByTestId('centerpoint-select').getAttribute('aria-pressed'), 'true');
        await handle.waitFor({ state: 'hidden' });
        assert.equal(await handle.count(), 0, 'reviewing another candidate must release the formal box handles');
        await review(() => plus.click()); await review(() => nextRow.getByTestId('centerpoint-reject').click());
        await panel.waitFor({ state: 'hidden' }); assert.deepEqual((await formal()).center, adjusted.center);
        assert.equal((await page.evaluate(inspectScene)).accepted.length, expected.length);
        console.log('PASS formal-to-candidate switch and reject without changing the formal box');
    } finally {
        await browser?.close(); await server?.close(); fs.rmSync(temp, { recursive: true, force: true });
    }
}
main().catch(error => { console.error(error); process.exitCode = 1; });